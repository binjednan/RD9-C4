def _fcu_rows():
    S = json.load(open(FCU_SCHED, encoding="utf-8"))
    rows = {}
    for k, r in S.items():
        parts = k.split()
        if len(parts) > 1 and len(set(parts)) == 1:      # duplicated OCR keys: the manual repair replaces them
            continue
        rows[k] = dict(r)
    rows.update({k: dict(v) for k, v in _MANUAL.items()})
    for k, r in rows.items():
        if k.startswith("FCU-4-"): r["qty"] = _QTY_TYPICAL
    return rows


def enrich(M):
    """FCU elements: attach the AC-106 schedule row (capacity, water flow, air flow, coil conditions, electrical power)."""
    rows = _fcu_rows()
    fcus = [e for e in M["els"] if e["t"] == "fcu"]
    resolved = {e["mark"]: _MARK_TO_KEY.get(e["mark"], e["mark"]) for e in fcus if _MARK_TO_KEY.get(e["mark"], e["mark"]) in rows}
    claimed = set(resolved.values())
    free = [k for k in rows if k not in claimed]
    n_tag = n_inf = 0
    for e in fcus:
        a = e.setdefault("a", {})
        key = None; note = None
        if e["mark"] in resolved:
            key = resolved[e["mark"]]; note = _INFER.get(e["mark"])
        elif e["mark"] == "FCU-?":
            lv, u = e["l"], e.get("u")
            cand = [k for k in free if k.startswith(f"FCU-{lv}-{u.split('-')[1]}.")] if u else [k for k in free if k == f"FCU-{lv}-L"]
            if len(cand) == 1:
                key = cand[0]; note = "الوحدة بلا وسم مقروء في المسقط؛ الصف استُنتج بالإقصاء داخل الشقة/الدور (الوحيد الذي لا عنصر له في الجدول)"
        if key is None:
            continue
        r = rows[key]
        a["sched_unit"] = key
        a["serving"] = r["serving"]
        a["fcu_kind"] = _KIND_AR.get(r["remarks"], r["remarks"])
        a["cap_total_kw"] = r["tkw"]; a["cap_sens_kw"] = r["skw"]; a["chw_gpm"] = r["gpm"]
        a["chw_pipe"] = f'{r["pin"]}" ({r["pmm"]:g} مم)'; a["air_lps"] = r["lps"]; a["esp_pa"] = r["pa"]
