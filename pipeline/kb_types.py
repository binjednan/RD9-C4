def T(n, cf, sp=None, asm=None, sr=None, adv=None, mt=None):
    d = {"n": n, "cf": cf, "sp": sp or []}
    if asm: d["asm"] = asm
    if sr: d["sr"] = sr
    if adv: d["adv"] = adv
    if mt: d["mt"] = mt
    return d


def _dims(els):
    """median (long, short) side in cm of the plan outlines of the given elements"""
    ws, ds = [], []
    for e in els:
        g = e["g"]
        if g[0] == "p":
            xs = [p[0] for p in g[1]]; ys = [p[1] for p in g[1]]
            a, b = max(xs) - min(xs), max(ys) - min(ys)
        elif g[0] == "r":
            a, b = abs(g[3] - g[1]), abs(g[4] - g[2])
        else:
            continue
        ws.append(max(a, b)); ds.append(min(a, b))
    if not ws: return None
    return round(statistics.median(ws)), round(statistics.median(ds))


def _dist(els, key, top=4, rnd=0):
    c = collections.Counter()
    for e in els:
        v = (e.get("a") or {}).get(key)
        if v is None: continue
        c[round(v, rnd) if isinstance(v, float) else v] += 1
    return c.most_common(top)


